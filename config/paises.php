/**
 * Ordem alfabética portuguesa. Sem isto, 'Áustria', 'Índia' e 'Ómã' caíam no
 * fim da lista: a comparação é byte a byte e os acentuados ficam acima de 'z'.
 */
$chave = static fn (string $nome): string => strtr(mb_strtolower($nome), [
    'á' => 'a', 'à' => 'a', 'â' => 'a', 'ã' => 'a', 'ä' => 'a',
    'é' => 'e', 'è' => 'e', 'ê' => 'e', 'ë' => 'e',
    'í' => 'i', 'ì' => 'i', 'î' => 'i', 'ï' => 'i',
    'ó' => 'o', 'ò' => 'o', 'ô' => 'o', 'õ' => 'o', 'ö' => 'o',
    'ú' => 'u', 'ù' => 'u', 'û' => 'u', 'ü' => 'u',
    'ç' => 'c', 'ñ' => 'n',
]);

usort($paises, static fn (array $a, array $b): int => $chave($a['nome']) <=> $chave($b['nome']));

return $paises;
